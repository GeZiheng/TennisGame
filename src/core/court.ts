/**
 * 场地尺寸与物理常量。
 *
 * 单位和真实球场一致（米），因为所有手感都是从这里长出来的：
 * 球速 30 m/s、网高 0.914、场地 12 米，这些数字决定了「一拍打过去要多久」。
 * 想让节奏更快只能调球速，不能偷偷把场地缩小——那会让所有其它参数跟着失准。
 *
 * 坐标约定：玩家在 +z 侧，球从 -z 飞过来。y 朝上。
 */

/* ---------------- 场地 ---------------- */

/** 单打边线半宽 */
export const HALF_WIDTH = 4.115;
/** 底线 z（玩家身后一点） */
export const BASELINE_Z = 1.5;
/** 球网 z */
export const NET_Z = -10.5;
/** 球网中心高度（网柱处更高，这里取中点） */
export const NET_H = 0.914;
/** 发球线 z */
export const SERVICE_Z = -4.5;

/**
 * 对面的练习墙：放在网后 1.4 米。
 *
 * 这个距离是被「球能不能自己飞回来」逼出来的，不是随便定的：
 * 再远 2 米，球撞墙后的动能就不够回到玩家手边，会停在网前不动，
 * 玩家只能看着球躺在那里。对墙打的前提是球必须自己回来。
 */
export const WALL_Z = -11.9;
export const WALL_H = 5.2;

/* ---------------- 玩家与击球 ---------------- */

/**
 * 击球平面 z。球穿过这个平面就是「该击球了」。
 * 放在球拍前方一点点，而不是球拍中心——真实击球点在拍面上，不在手腕上。
 */
export const HIT_Z = 0.3;

/**
 * 球拍的握点（世界系）。
 *
 * z 取 HIT_Z：拍面中心就落在击球面上。之前是 0，而判定平面在 0.3，
 * 结果是「球在拍子前方 30 厘米处被打中」——视觉上球凭空拐弯，一直没人注意到。
 *
 * y = 1.3：握点（虎口）的高度，大致是胸口中线。**这个数直接决定横握时拍面有多高**——
 * 横握时拍面是水平的，中心就落在握点高度上（`faceCenter` 只加 0.6m 的柄长，杆子横过去
 * 时 y 分量为 0）。竖握时中心 = 握点 + 0.6 = 1.9m。
 *
 * 历史上这两档都试过：0.85（横握拍面 0.85m）实测来球 1.51m，球高出拍面 66cm，
 * 玩家每球都要超大上挥；1.0 配自适应喂球能打，但横握拍面只有 1.0m，而弹地喂球
 * 到面普遍在 1.3m 以上（竖直判定半轴只有 0.23m），横握玩家必须一直举着拍子等球，
 * 自动走位甚至要靠后退 1.35m 以上才能把球「等到」拍面高度（见 `auto-move.ts`）。
 * 1.3 是**胸口中线的自然持拍高度**：横握拍面 1.3m 与来球高度同高，人站着不动就能挡；
 * 竖握 1.9m 属于略高的球，喂球会照拍面自适应，不需要玩家额外上挥。
 *
 * 抬高握点的代价是**低球变难**（拍面最低只能到握点高度）：对打里回球机的
 * 到面高度带（`machine.ts` 的 `ARRIVE_Y_*`）跟着上移，墙打喂球本来就瞄拍面中心，
 * 所以两边都不需要玩家蹲下。
 *
 * 这个点之后会被「走位」系统移动，所以 Racket 的位姿是每帧送进来的，
 * 不是从常量读的；这里只是它的初始位置。
 */
export const RACKET_POS: [number, number, number] = [0, 1.3, HIT_Z];

/**
 * 拍面几何。真实网球拍的拍框内沿：宽 30cm、长 38cm。
 *
 * 这两个数字现在**真的参与击球判定**了（见 core/racket.ts）：
 * 球心到拍面平面的距离小于球半径、且投影落在椭圆内，才算打中。
 * 改这两个值会直接改变可击球面积——不再只是外观参数。
 */
export const FACE_RX = 0.15;
export const FACE_RY = 0.19;
/** 拍面中心在球拍局部系里的 y 偏移（握点到拍面中心），等于球拍长度的一半多一点。 */
export const FACE_CY = 0.6;
/**
 * 拍面判定容差（米）。真实拍框本身有厚度、甜区外还有一圈框，
 * 给 2cm 让「擦框」也能算击中，不给的话边缘会有明显的「明明碰到了却判空」。
 *
 * 从 1.2cm 加到 2cm 是因为严格碰撞上线后暴露了一类系统性漏判：
 * 位姿是网络传来又平滑过的，球穿过拍面的那一刻，判定用的拍面比玩家手里
 * 那把（也比他屏幕上看到的）平均晚 20–60ms——快速挥拍里就是几厘米。
 * 视觉上球明显蹭到了框，判定说没有。2cm 大致覆盖这段延迟造成的位移。
 */
export const FACE_MARGIN = 0.02;

/* ---------------- 喂球散布 ---------------- */

/**
 * 喂球的目标不是「精确送到拍面中心」，而是「弹起后的最高点落在拍面附近」。
 *
 * 这两者看起来差不多，实际差在**约束的强弱**上，而强弱直接决定手感真不真：
 *
 *   - 精确瞄中心：每球都像被吸到拍线上，位置一模一样。玩家看两球就会发现
 *     「球永远落在我正前方」，不需要判方向，只需要判时间——半个游戏没了。
 *   - 只要求顶点在附近：每球会差十几厘米，玩家得真的看一眼球在哪一侧，
 *     同时又要判时机。这才是接球。
 *
 * 但散布不能大过判定盘，否则就退回「总是够不到」。判定椭圆的等效半轴是
 * FACE_RX + BALL_R + FACE_MARGIN ≈ 0.203（横）、FACE_RY + BALL_R + FACE_MARGIN ≈ 0.243（竖）。
 *
 * 取 0.12 / 0.10 而不是贴着半轴取值，是因为横向和竖直会**同时**偏：两轴都取满时
 * 合成偏离是 sqrt((0.16/0.203)² + (0.14/0.243)²) ≈ 0.98，几乎贴着盘边——
 * 再叠上「球到面时拍面还在动」的那点跟随误差，就会偶发判空。
 * 0.12 / 0.10 合成后约 0.72，留出三成余量，实测甜区读数落在 0.45–0.75，
 * 明显散开但一定在盘内。
 */
export const FEED_APEX_DX = 0.12;
export const FEED_APEX_DY = 0.1;

/**
 * 顶点落在拍面**之后**多远（米）。这一段是「球还在缓升、送到你手上」。
 *
 * 为什么不取负值（顶点在拍面前、球已下落）：下落球接到时是迎面砸下来的，
 * 手感更硬，而且「顶点越靠前，弹起点就得越远」——正是「落点离我太远」那条反馈。
 *
 * 为什么不把 back 压到 0.2 以内（顶点几乎贴住拍面）：那要求落点退到 2.2m 以上，
 * 又变成落点太远。0.55–0.85 对应落点 1.55–1.85m，是上一轮真机验证过、
 * 落点舒服的那一段；代价是球到拍面时还有 1.3–1.9 m/s 的上升速度，
 * 也就是「往上送到你手上」而不是「悬停在那里」。
 *
 * back 也提供这一球的纵向变化：球有时候顶点近一点（更平），有时候远一点（更拱）。
 */
export const FEED_APEX_BACK_MIN = 0.55;
export const FEED_APEX_BACK_MAX = 0.85;

/**
 * 弹起顶点在落点前方多远（米）。
 *
 * 实测（scripts/probe-feed-scan2.cjs + 顶点回算）：来球高度约 1.6m 时，
 * 弹起水平速度约 3.5–5.0 m/s，爬升到顶约 0.5–0.6s，乘积就是 2.3–2.45m。
 * 取 2.40 做中值，再用候选落点兜住个体差异。
 *
 * 握点抬到 1.3 之后参考握法的到面高度是 1.9m，真实 lead 变大到约 2.5m——按 2.40 算，
 * 顶点会比设计值更靠近拍面 0.1m。这个方向是安全的（球到面时仍在上升），实测
 * 拍面高 1.8m、落点 1.6–1.8m 时顶点还在拍面**之后** 0.50–0.71m，仍在 0.55–0.85 附近，
 * 所以不改这个数；真要改必须重跑 probe-feed-scan2 看顶点位置，别凭直觉估。
 *
 * 这个数偏 0.1m，顶点就整体前后移 0.1m——它决定了「顶点在拍面之后多远」，
 * 也就是球到拍面时还在爬升还是已经开始下落。别凭直觉估，要重测。
 */
export const FEED_APEX_LEAD = 2.4;

/**
 * 回球允许偏离拍面中心多少（占判定半径的比例，1.0 就是盘边）。
 *
 * 回球补偿（physics.liftOverNet）原来在可行弧线里挑**最居中**的那条，
 * 还会按 0.1 的步长细化一圈——每一拍都送到甜区正中央。结果是回球永远在
 * 同一个点上等你，玩家只要判时间、不用判方向。
 *
 * 0.55 的意思是：只要球能落在拍面 55% 半径以内，都是合格的回球，
 * 具体选哪条弧线随机挑。于是回球会有十几厘米的自然漂移，
 * 但绝不会漂到「够不着」（盘边才是 1.0）。
 */
export const RETURN_OFF_TOL = 0.55;

/**
 * 击球时间窗（毫秒）。
 *
 * 严格碰撞上线后，这个窗口不再决定「打不打得中」（那是 sweepFace 的几何判定），
 * 只回答「这一下算不算你挥的」：球可能正好撞上静止的拍子，那不该算一次击球。
 * 太小→「明明挥了却打空」，太大→随便乱挥都能中；±150ms 大致是一次完整挥拍的前后各半。
 */
export const HIT_WINDOW_MS = 150;

/** 一次挥拍只能打一个球：防止连续挥动时把后续每个球都自动吸过来。 */
export const STROKE_COOLDOWN_MS = 260;

/* ---------------- 球 ---------------- */

export const BALL_R = 0.0335;
