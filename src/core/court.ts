export const BALL_RENDER_R = 0.057;
export const BALL_M = 0.057;
/** 球体迎风面积 */
export const BALL_AREA = Math.PI * BALL_R * BALL_R;

/** 空气密度 kg/m³ */
export const RHO = 1.2;
/** 网球绒毛表面的阻力系数，比光滑球高不少——这正是网球高速衰减极快的原因 */
export const DRAG_CD = 0.55;
/** 马格努斯升力系数，取偏保守的值 */
export const MAGNUS_CL = 0.22;

export const GRAVITY = 9.80665;

/** 硬地：竖直速度恢复系数。真实网球落地后大约弹回到 55% 高度，换算成速度约 0.75。 */
export const GROUND_REST = 0.76;
export const GROUND_FRIC = 0.74;
/** 练习墙是弹性挡板（软垫或球网兜），比地面更吃能量，但不能太低——
 * 低于 0.7 的话球撞完墙就飞不回玩家手边，对墙打直接没法进行。 */
export const WALL_REST = 0.76;
/** 旋转衰减时间常数（秒）。真实网球大约 4 秒衰减到 37%。 */
export const SPIN_TAU = 4.0;

/* ---------------- 挥拍 → 出球 ---------------- */

/**
 * 等效力臂：手机握在那里，到拍头的距离。
 *
 * 取真实球拍长度 0.68m 而不是手机的实际长度，是因为算出来的拍头速度最终会被
 * SPEED_GAIN 放大，两个系数只要乘积对上，手感就一样；用真实值至少让中间的
 * 「拍头速度」这个量还能对得上物理。
 */
export const SWING_ARM = 0.68;

/**
 * 速度放大系数。
 *
 * 真实挥拍拍头速度 22–35 m/s，手机握持大约只能测到 8–14（没杠杆、幅度小），
 * 所以放大 2.4 倍。这个数字直接决定「全力挥」打出来是不是够快——
 * 20 是能舒服过网的下限，26 是甜蜜点，超过 34 球就压不住了。
 */
export const SPEED_GAIN = 2.4;
/**
 * 出球速度区间（m/s）。
 *
 * 20→18 / 42→32：原来全力一挥 42 m/s，球 0.3 秒就飞到 11 米外的墙上，
 * 玩家看见的只有一道黄影。降一档之后回球落在网前一两米、拍与拍之间有余裕。
 *
 * 下限 18 是**物理底线**，不是手感偏好：球从墙上弹回来还要再过一次网，
 * 出球慢于这个值，回球不是擦网就是在中场弹一下之后趴着到玩家面前
 * （模拟里实测 13–16 m/s 全部如此，五种力度档位直接挂三档）。
 * 想更慢只能改墙的弹性或墙距，不能再压这个数。
 */
export const SPEED_MIN = 18;
export const SPEED_MAX = 32;

/**
 * 判定「这一下算挥拍」的角速度门槛（rad/s）。
 *
 * 3.0 rad/s ≈ 172°/s。比原来的 3.6 低一档，是因为角速度经常来自「姿态差分」兜底：
 * 差分给的是两帧之间的**平均**角速度，会把峰值削掉 15–25%，用原来的门槛会
 * 出现「真的用力挥了却差一点点」的漏检。正常挥一下手机，手腕角速度很容易到 300°/s 以上。
 */
export const SWING_THRESHOLD = 3.0;

/**
 * 一次挥拍从起速到收尾允许的最长时长。
 *
 * 超过它就不是「挥」而是「转」——比如举着手机缓慢转身，角速度能稳定在两三 rad/s
 * 并持续好几秒。没有这道闸，那种动作会被当成一次绵长的挥拍。
 */
export const SWING_MAX_MS = 450;

/**
 * 判定「峰已经过了」的回落比例：角速度跌到峰值的这个比例以下，就算挥完了。
 *
 * 这是整条链路里**对手感最贵的一个参数**。结算发生在峰值之后，「球什么时候被打出去」
 * 就跟着晚多久——玩家手已经挥完，球还在击球面上悬着，然后才弹走。
 *
 *   0.75（旧值）：要等挥拍基本收住才结算，峰值后 50–90ms。人能察觉的
 *     视触同步误差阈值大约 50–80ms，这个值正好落在「明显能感觉到」的区间里。
 *   0.90（现值）：跌一档就结算，峰值后 1–2 帧（16–33ms），低于感知阈值。
 *
 * 不能取 1.0：平台段（60Hz 发包 + 30Hz 姿态造成的重复值）上 w 恒等于 peakW，
 * 「跌到峰值以下」永远不成立，一次都不会结算。0.9 留了足够余量区分「还在峰顶」
 * 和「开始下落」。
 */
export const FALL_RATIO = 0.9;

/** 物理定步长。240Hz 下 40 m/s 的球每步只走 16.7cm，不会隧穿。 */
export const PHYS_DT = 1 / 240;

/* ---------------- 对打场地 ---------------- */

/**
 * 对打模式：把场子沿球网镜像出另一半。
 *
 * 墙打模式里球网后面 1.4 米就是练习墙（`WALL_Z`），那不是一个场地——它存在的
 * 唯一理由是「球必须自己飞回来」。对打要有对手站的地方，所以对手侧完全按
 * 球网镜像：`2 × NET_Z − 本地值`。
 *
 * 镜像后两半各 10.8 米（玩家击球面到网），合计 21.6 米。真实球场底线到网
 * 11.885 米，这里短 9%，因为击球面本来就在底线内侧一点（`HIT_Z`=0.3，
 * `BASELINE_Z`=1.5），不是场地被偷偷缩了。
 */
export const OPP_HIT_Z = 2 * NET_Z - HIT_Z;
export const OPP_BASELINE_Z = 2 * NET_Z - BASELINE_Z;

/**
 * 对打模式下「球已经飞过这个半场」的余量（米）。
 *
 * 球可以合法地飞过底线之后才落地（出界），所以判死线要放在底线外面，
 * 不能压着底线判——压线判会把「压线好球」直接判成出界。
 */
export const DUEL_PAD = 1.2;
